//! Call tracing for working out what a game (or Steam's DRM wrapper) asks
//! for, written to the steamclient log (STEAMINRUST_STEAMCLIENT_LOG):
//!
//! - every export call, with its first arguments and result;
//! - every call to an interface method we don't implement (those answer 0),
//!   by interface and method name.
//!
//! Each is logged its first {LIMIT} times only, so per-frame calls don't
//! flood the log. Off (no cost but a check) without the log variable.

use crate::vt::Fp;
use std::collections::HashMap;
use std::sync::Mutex;

const LIMIT: u32 = 3;

fn on() -> bool {
    static ON: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *ON.get_or_init(|| std::env::var_os(crate::protocol::ENV_LOG).is_some())
}

fn first_times(key: &str) -> bool {
    static SEEN: Mutex<Option<HashMap<String, u32>>> = Mutex::new(None);
    let mut seen = SEEN.lock().unwrap_or_else(|e| e.into_inner());
    let n = seen.get_or_insert_with(HashMap::new).entry(key.to_string()).or_insert(0);
    *n += 1;
    *n <= LIMIT
}

pub fn export(name: &str, args: [usize; 3], result: usize) {
    if on() && first_times(name) {
        crate::log!("export {name}({:#x}, {:#x}, {:#x}) -> {result:#x}", args[0], args[1], args[2]);
    }
}

/// Names of implemented methods whose 32-bit calls are logged.
static CALLS: Mutex<Vec<String>> = Mutex::new(Vec::new());

/// With tracing on, an id for logging calls to an implemented method (the
/// 32-bit trampolines call [`called`] with it before the method).
#[cfg_attr(not(target_arch = "x86"), allow(dead_code))]
pub fn call_id(kind: &str, method: &str) -> Option<u32> {
    if !on() {
        return None;
    }
    let mut calls = CALLS.lock().unwrap_or_else(|e| e.into_inner());
    calls.push(format!("{kind}::{method}"));
    Some(calls.len() as u32 - 1)
}

/// Logged first: the method and its first three stack arguments.
#[cfg_attr(not(target_arch = "x86"), allow(dead_code))]
pub extern "C" fn called(id: u32, a: u32, b: u32, c: u32) {
    let name = CALLS.lock().map(|n| n.get(id as usize).cloned()).ok().flatten().unwrap_or_default();
    if first_times(&format!("call {name}")) {
        crate::log!("call {name}({a:#x}, {b:#x}, {c:#x})");
    }
}

/// Names of the traced stub slots handed out so far.
static NAMES: Mutex<Vec<String>> = Mutex::new(Vec::new());

/// A stub for an unimplemented method that logs its name when called;
/// `None` when tracing is off or all 512 traced stubs are in use (the caller
/// then uses the silent one).
pub fn stub(kind: &str, method: &str) -> Option<Fp> {
    if !on() {
        return None;
    }
    let mut names = NAMES.lock().unwrap_or_else(|e| e.into_inner());
    let k = names.len();
    let f = *TRACED.get(k)? as Fp;
    names.push(format!("{kind}::{method}"));
    Some(f)
}

extern "C" fn traced<const K: usize>() -> usize {
    let name = NAMES.lock().map(|n| n.get(K).cloned()).ok().flatten().unwrap_or_default();
    if first_times(&name) {
        crate::log!("unimplemented {name} called -> 0");
    }
    0
}

